FOUNDER_RESEARCH_PACK_KEY = "founder_research"
FOUNDER_RESEARCH_PACK_TAG = f"pack:{FOUNDER_RESEARCH_PACK_KEY}"


def _card(
    key: str,
    group: str,
    title: str,
    intent: str,
    trigger_summary: str,
    recommended_reply: str,
    avoid_reply: str = "",
    extra_tags: str = "",
) -> dict:
    tags = [FOUNDER_RESEARCH_PACK_TAG, f"key:{key}", f"group:{group}"]
    if extra_tags:
        tags.extend(tag.strip() for tag in extra_tags.split(",") if tag.strip())
    return {
        "key": key,
        "group": group,
        "title": title,
        "intent": intent,
        "trigger_summary": trigger_summary,
        "recommended_reply": recommended_reply,
        "avoid_reply": avoid_reply,
        "tags": ",".join(tags),
        "status": "active",
    }


